FONT = "Leelawadee UI"
NAVY = RGBColor(0x1B, 0x2A, 0x4A)
ORANGE = RGBColor(0xE8, 0x7A, 0x1E)
TEAL = RGBColor(0x0E, 0x7C, 0x7B)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)
GRAY = RGBColor(0x55, 0x5F, 0x6E)
LIGHT = RGBColor(0xF2, 0xF5, 0xF9)

SW, SH = Inches(13.333), Inches(7.5)


def new_deck():
    prs = Presentation()
    prs.slide_width, prs.slide_height = SW, SH
    return prs


def _bg(slide, color):
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = color


def _box(slide, l, t, w, h):
    box = slide.shapes.add_textbox(l, t, w, h)
    box.text_frame.word_wrap = True
    return box


def _set(p, text, size, color, bold=False, align=PP_ALIGN.LEFT):
    p.text = text
    p.alignment = align
    for r in p.runs:
        r.font.name = FONT
        r.font.size = Pt(size)
        r.font.color.rgb = color
        r.font.bold = bold


def add_title_slide(prs, title, subtitle, lines):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    _bg(s, NAVY)
    tf = _box(s, Inches(0.9), Inches(2.0), Inches(11.5), Inches(1.6)).text_frame
    _set(tf.paragraphs[0], title, 48, WHITE, bold=True)
    tf2 = _box(s, Inches(0.9), Inches(3.5), Inches(11.5), Inches(0.9)).text_frame
    _set(tf2.paragraphs[0], subtitle, 26, ORANGE, bold=True)
    tf3 = _box(s, Inches(0.9), Inches(4.6), Inches(11.5), Inches(2.2)).text_frame
    for i, line in enumerate(lines):
        p = tf3.paragraphs[0] if i == 0 else tf3.add_paragraph()
        _set(p, line, 17, RGBColor(0xC9, 0xD4, 0xE5))
    return s


def add_section(prs, kicker, title, duration, points):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    _bg(s, TEAL)
    tf = _box(s, Inches(0.9), Inches(1.6), Inches(11.5), Inches(0.7)).text_frame
    _set(tf.paragraphs[0], kicker, 20, RGBColor(0xBF, 0xE8, 0xE7), bold=True)
    tf2 = _box(s, Inches(0.9), Inches(2.3), Inches(11.5), Inches(1.5)).text_frame
    _set(tf2.paragraphs[0], title, 40, WHITE, bold=True)
    tf3 = _box(s, Inches(0.9), Inches(3.8), Inches(11.5), Inches(0.6)).text_frame
    _set(tf3.paragraphs[0], duration, 18, RGBColor(0xBF, 0xE8, 0xE7), bold=True)
    tf4 = _box(s, Inches(0.9), Inches(4.5), Inches(11.5), Inches(2.4)).text_frame
    for i, pt in enumerate(points):
        p = tf4.paragraphs[0] if i == 0 else tf4.add_paragraph()
        _set(p, "•  " + pt, 17, WHITE)
    return s


def add_content(prs, title, bullets, kicker=None, notes=None, workshop=False):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    _bg(s, WHITE)
    bar = s.shapes.add_shape(1, 0, 0, SW, Inches(1.25))
    bar.fill.solid()
    bar.fill.fore_color.rgb = ORANGE if workshop else NAVY
    bar.line.fill.background()
    bar.text_frame.word_wrap = True
    bar.text_frame.vertical_anchor = MSO_ANCHOR.MIDDLE
    bar.text_frame.margin_left = Inches(0.6)
    _set(bar.text_frame.paragraphs[0], title, 28, WHITE, bold=True)

    top = Inches(1.45)
    if kicker:
        ktf = _box(s, Inches(0.65), top, Inches(12.0), Inches(0.5)).text_frame
        _set(ktf.paragraphs[0], kicker, 15, ORANGE if workshop else TEAL, bold=True)
        top = Inches(2.0)

    tf = _box(s, Inches(0.65), top, Inches(12.0), SH - top - Inches(0.4)).text_frame
    first = True
    for b in bullets:
        if b.startswith(">>"):
            p = tf.paragraphs[0] if first else tf.add_paragraph()
            _set(p, "–  " + b[2:].strip(), 16, GRAY)
            p.level = 1
        elif b == "":
            p = tf.paragraphs[0] if first else tf.add_paragraph()
            _set(p, "", 8, GRAY)
        else:
            p = tf.paragraphs[0] if first else tf.add_paragraph()
            _set(p, "•  " + b, 19, NAVY)
        first = False

    if notes:
        s.notes_slide.notes_text_frame.text = notes
    return s


